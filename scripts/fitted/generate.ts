/**
 * Generates `packages/chromatic/src/model-v2.ts`, the coefficients of the `v2` colour model.
 *
 * The fit lives next to this script (`./fit.ts`, with the Tailwind v4 data in `./tailwind-v4.ts`); the playground's
 * chroma lab runs the same code interactively. This script snapshots it with `DEFAULT_TAILWIND_FIT_OPTIONS` so the
 * published packages never run the solver.
 *
 * Usage:
 *   pnpm run generate:fitted          # rewrite the file
 *   pnpm run generate:fitted --check  # exit 1 when the committed file is out of date
 */

import type { FitBlock } from './fit'

import { readFileSync, writeFileSync } from 'node:fs'
import { argv, exit } from 'node:process'
import { fileURLToPath } from 'node:url'

import {
  crossValidateTailwindFit,
  DEFAULT_TAILWIND_FIT_OPTIONS,
  fitTailwind,
  reportAgainstTailwind,
} from './fit'

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
const outputPath = fileURLToPath(new URL('../../packages/chromatic/src/model-v2.ts', import.meta.url))

const fit = fitTailwind(DEFAULT_TAILWIND_FIT_OPTIONS)
const report = reportAgainstTailwind(fit.predict)
const crossValidation = crossValidateTailwindFit(DEFAULT_TAILWIND_FIT_OPTIONS)

function block(b: FitBlock, indent: string): string {
  return [
    '{',
    `${indent}  curves: ${rows(b.curves, `${indent}  `)},`,
    `${indent}  curvesHaveConst: ${b.curvesHaveConst},`,
    `${indent}  intercepts: ${numbers(b.intercepts)},`,
    `${indent}  weights: ${rows(b.weights, `${indent}  `)},`,
    `${indent}}`,
  ].join('\n')
}

function num(value: number): string {
  const rounded = Number(value.toFixed(6))
  return Object.is(rounded, -0) ? '0' : String(rounded)
}

function numbers(values: number[]): string {
  return `[${values.map(num).join(', ')}]`
}

function rows(values: number[][], indent: string): string {
  return `[\n${values.map(row => `${indent}  ${numbers(row)},`).join('\n')}\n${indent}]`
}

const { chroma, harmonics, hueDrift, override, rank } = DEFAULT_TAILWIND_FIT_OPTIONS
const description = [
  `lightness: ${rank === 'per-shade' ? 'per-shade Fourier series' : `${rank} shared hue curve(s)`}, ${harmonics} harmonics`,
  chroma.mode === 'relative'
    ? `chroma: share of sRGB (${chroma.ratioHarmonics} harmonics) × exact sRGB max, refitted per shade with ${chroma.harmonics} harmonics`
    : `chroma: ${harmonics} harmonics`,
  hueDrift ? 'hue drift' : 'no hue drift',
  `sRGB window ${override.center}° ± ${override.width / 2}° (${Math.round(override.lightRatio * 100)}% / ${Math.round(override.midRatio * 100)}% of sRGB max)`,
].join(', ')

const content = `// Generated by \`pnpm run generate:fitted\` (scripts/fitted/generate.ts). Do not edit by hand.
//
// Colour model v2. Released versions are frozen: a different fit becomes a new version.\n// Fit of the Tailwind CSS v4 palette: ${description}.
// ΔE (OKLab × 100) against Tailwind v4: RMS ${report.rms.toFixed(2)}, max ${report.max.toFixed(1)}; leave-one-family-out RMS ${crossValidation.rms.toFixed(2)}.

import type { FittedModel } from './fitted'

export const MODEL_V2: FittedModel = {
  chroma: ${block(fit.chroma, '  ')},
  hueDrift: ${fit.hueDrift ? block(fit.hueDrift, '  ') : 'null'},
  lightness: ${block(fit.lightness, '  ')},
  shades: ${numbers(SHADES)},
}
`

if (argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(outputPath, 'utf8')
  }
  catch {}

  if (current !== content) {
    console.error('model-v2.ts is out of date, run `pnpm run generate:fitted`')
    exit(1)
  }
  console.info('model-v2.ts is up to date')
}
else {
  writeFileSync(outputPath, content)
  console.info(`wrote ${outputPath}\n  ${description}\n  ΔE RMS ${report.rms.toFixed(2)}, max ${report.max.toFixed(1)}, CV RMS ${crossValidation.rms.toFixed(2)}`)
}
